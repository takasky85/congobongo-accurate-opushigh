class synth
{
public:
	enum { BASS = 0, CONGA_L, CONGA_H, RIM, NUM_VOICES };

	// volts at SOU for one hit are scaled by 'gain' (set to 1/2.216 to be in units where the
	// SN76489A full-range output (4 channels at max volume) is 1.0 -- see README)
	void set_rate(double rate, double gain = 1.0)
	{
		m_gain = gain;
		for (int v = 0; v < NUM_VOICES; v++) {
			m_n[v] = 0;
			const mode_def *md; size_t n;
			get(v, md, n);
			for (size_t k = 0; k < n && k < MAX_MODES; k++) {
				m_z[v][k] = std::exp(std::complex<double>(md[k].sr, md[k].si) / rate);
				m_c[v][k] = std::complex<double>(md[k].cr, md[k].ci);
				m_y[v][k] = 0;
				m_n[v] = k + 1;
			}
		}
	}

	void reset() { for (auto &v : m_y) for (auto &y : v) y = 0; }

	// Release of the trigger bit (7416 output falls): start the voice.
	// Re-trigger while ringing just adds (linear approximation).
	void trigger(int voice, double level = 1.0)
	{
		for (size_t k = 0; k < m_n[voice]; k++)
			m_y[voice][k] += m_c[voice][k] * level;
	}

	// one output sample per voice (volts at SOU * gain); call once per sample
	void tick_voices(double *out)
	{
		for (int v = 0; v < NUM_VOICES; v++) {
			double sum = 0;
			for (size_t k = 0; k < m_n[v]; k++) {
				sum += m_y[v][k].real();
				std::complex<double> y = m_y[v][k] * m_z[v][k];
				// flush denormals / inaudible state
				if (std::norm(y) < 1e-30) y = 0;
				m_y[v][k] = y;
			}
			out[v] = sum * m_gain;
		}
	}

	// returns one output sample (volts at SOU * gain); call once per sample
	double tick()
	{
		double o[NUM_VOICES];
		tick_voices(o);
		double sum = 0;
		for (int v = 0; v < NUM_VOICES; v++) sum += o[v];
		return sum;
	}

private:
	static constexpr size_t MAX_MODES = 64;

	static void get(int v, const mode_def *&md, size_t &n)
	{
		switch (v) {
		case BASS:    md = MODES_BASS;    n = sizeof(MODES_BASS) / sizeof(mode_def); break;
		case CONGA_L: md = MODES_CONGA_L; n = sizeof(MODES_CONGA_L) / sizeof(mode_def); break;
		case CONGA_H: md = MODES_CONGA_H; n = sizeof(MODES_CONGA_H) / sizeof(mode_def); break;
		default:      md = MODES_RIM;     n = sizeof(MODES_RIM) / sizeof(mode_def); break;
		}
	}

	double m_gain = 1.0;
	size_t m_n[NUM_VOICES] = {};
	std::complex<double> m_z[NUM_VOICES][MAX_MODES];
	std::complex<double> m_c[NUM_VOICES][MAX_MODES];
	std::complex<double> m_y[NUM_VOICES][MAX_MODES];
};

